// Builds the static frontend into dist/ for Vercel (or any static host): public/, the shared
// rules modules the browser imports, and a config.js pointing at the separately hosted game server.
// Usage: GAME_SERVER_URL=https://your-app.onrender.com node scripts/build-static.js [--require-server-url]
import { cpSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';

const at = (p) => new URL(p, new URL('..', import.meta.url));
const out = at('dist/');
// vercel.json passes the flag explicitly, since VERCEL=1 can be switched off in project settings.
const onVercel = Boolean(process.env.VERCEL) || process.argv.includes('--require-server-url');

function fail(message) {
  console.error(`build-static: ${message}`);
  process.exit(1);
}

// Accept "https://host", "host", "wss://host/ws" and normalize to the server's http(s) origin.
let serverUrl = '';
const raw = (process.env.GAME_SERVER_URL ?? '').trim();
if (raw) {
  let u;
  try {
    u = new URL(raw.includes('://') ? raw : `https://${raw}`);
  } catch {
    fail(`GAME_SERVER_URL is not a valid URL: ${raw}`);
  }
  if (u.protocol === 'wss:') u.protocol = 'https:';
  if (u.protocol === 'ws:') u.protocol = 'http:';
  if (u.protocol !== 'https:' && u.protocol !== 'http:') fail(`GAME_SERVER_URL must be http(s) or ws(s): ${raw}`);
  const local = ['localhost', '127.0.0.1', '[::1]'].includes(u.hostname);
  // An https page may not open an insecure ws:// socket (mixed content).
  if (onVercel && u.protocol === 'http:' && !local) fail('GAME_SERVER_URL must use https:// on Vercel.');
  serverUrl = u.origin;
} else if (onVercel) {
  fail('Set the GAME_SERVER_URL environment variable in the Vercel project (e.g. https://color-block-coop.onrender.com).');
}

rmSync(out, { recursive: true, force: true });
cpSync(at('public/'), out, { recursive: true });
mkdirSync(new URL('shared/', out), { recursive: true });
for (const f of readdirSync(at('shared/'))) {
  // The worker only runs on the game server.
  if (f.endsWith('.js') && f !== 'gen-worker.js') cpSync(at(`shared/${f}`), new URL(`shared/${f}`, out));
}
writeFileSync(
  new URL('config.js', out),
  `// Generated by scripts/build-static.js. Do not edit.\nwindow.CB_CONFIG = ${JSON.stringify({ serverUrl })};\n`,
);
console.log(`build-static: wrote dist/ (game server: ${serverUrl || 'same origin'})`);
